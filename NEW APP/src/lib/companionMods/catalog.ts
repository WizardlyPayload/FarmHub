import type { SectionId } from "@/types/dashboard";

export type CompanionCategory =
  | "finance"
  | "economy"
  | "fields"
  | "contracts"
  | "livestock"
  | "production"
  | "storage"
  | "fleet"
  | "units";

export type CompanionCatalogEntry = {
  id: string;
  /** Fallback English title when i18n missing. */
  title: string;
  category: CompanionCategory;
  /** i18n key for long description of what the mod does. */
  descKey: string;
  /** Fallback English description. */
  desc: string;
  /** Related FarmHub section for deep-link; for `FOLDED_COMPANIONS` it must be the section that shows the mod's data. */
  relatedSection?: SectionId;
  /** Payload block key under companionMods (when live data exists). */
  liveKey?: string;
};

