export function catalogEntry(id: string | undefined | null): CompanionCatalogEntry | undefined {
  if (!id) return undefined;
  return COMPANION_CATALOG.find((e) => e.id === id);
}

export function categoryLabelKey(cat: CompanionCategory): string {
  return `companions.category.${cat}`;
}
