/** What FarmHub actually reads. A catalog row is not a live integration by itself. */
export function companionSupport(entry: CompanionCatalogEntry | undefined | null): CompanionSupport {
  if (!entry) return "unmapped";
  if (DETECTION_ONLY_IDS.has(entry.id)) return "detection-only";
  if (!entry.liveKey) return "unmapped";
  if (LIMITED_IDS.has(entry.id)) return "limited";
  return "live";
}

